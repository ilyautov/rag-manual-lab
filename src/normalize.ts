const STOP = new Set(('и в во не что он на я с со как а то все она так его но да ты к у же вы за бы по только ее мне было вот от меня еще нет о из ему когда даже ну ли если уже или ни быть был него до вас нибудь опять уж вам ведь там потом себя ничего ей может они тут где есть надо ней для мы тебя их чем была сам чтобы без чего раз тоже себе под будет ж тогда кто этот того потому этого какой какая какие какую совсем ним здесь этом один почти мой тем нее сейчас были куда зачем всех никогда можно при наконец об другой хоть после над больше тот через эти нас про всего них много разве эту моя впрочем свою этой перед иногда лучше чуть том такой им более всегда конечно всю между сколько как ли нужно нужен ваш вы').split(' '));

// Окончания от длинных к коротким. Это не морфология, а обрезка: «возврата» → «возврат».
// Глагольных «ат/ят» в списке нет: они резали существительные («возврат» → «возвр»), и формы
// одного слова расходились. «ть» срезается только после гласной: «вернуть», но не «стоимость».
const ENDINGS = ['иями', 'ями', 'ами', 'ией', 'иях', 'иям', 'ого', 'его', 'ому', 'ему', 'ыми', 'ими', 'ешь', 'ишь', 'ых', 'их', 'ые', 'ым', 'ую', 'юю', 'ая', 'яя', 'ое', 'ее', 'ой', 'ей', 'ий', 'ый', 'ом', 'ем', 'ам', 'ям', 'ах', 'ях', 'ов', 'ев', 'ии', 'ия', 'ие', 'ию', 'ью', 'ть', 'ет', 'ит', 'ут', 'ют', 'ла', 'ли', 'ло', 'а', 'я', 'о', 'е', 'ы', 'и', 'у', 'ю', 'ь', 'й'];
const MIN_STEM = 3;
const VOWEL_END = /[аеиоуыэюя]$/;

export function tokenize(text: string): string[] {
  return text.toLowerCase().replace(/ё/g, 'е').match(/[a-zа-я0-9%]+/g) ?? [];
}

export function stem(word: string): string {
  if (/^[0-9%]+$/.test(word)) return word;
  let w = word;
  // возвратная частица: «возвращается» → «возвращает»
  if (/(ся|сь)$/.test(w) && w.length - 2 >= MIN_STEM + 2) w = w.slice(0, -2);
  for (const e of ENDINGS) {
    if (!w.endsWith(e) || w.length - e.length < MIN_STEM) continue;
    if (e === 'ть' && !VOWEL_END.test(w.slice(0, -2))) continue;
    return w.slice(0, -e.length);
  }
  return w;
}

export function isStop(word: string): boolean {
  return STOP.has(word);
}

/** Термы для лексического поиска: токены без стоп-слов, обрезанные до основы. */
export function terms(text: string): string[] {
  return tokenize(text).filter((t) => !STOP.has(t)).map(stem);
}

/** Текст для сравнения подстрок: нижний регистр, ё → е, один пробел. */
export function flat(text: string): string {
  return text.toLowerCase().replace(/ё/g, 'е').replace(/\s+/g, ' ');
}

/** Грубая оценка числа токенов: 1 токен ≈ 4 символа. Для точного счёта нужен токенизатор модели. */
export function estimateTokens(text: string): number {
  return Math.ceil(text.length / 4);
}
